#!/usr/bin/env python3
"""Build preview/ from site/: relative asset paths and links (…/index.html) so the
draft works from a static file host such as raw.githack.com, and noindex,nofollow on
every page. Run after `npm run build`:  python3 scripts/make_preview.py
"""
import pathlib, re, shutil

root = pathlib.Path(__file__).resolve().parent.parent
site, prev = root / 'site', root / 'preview'
if prev.exists():
    shutil.rmtree(prev)
shutil.copytree(site, prev, ignore=shutil.ignore_patterns('CNAME', '.nojekyll'))

ROBOTS = '<meta name="robots" content="noindex,nofollow">'


def rel_url(url, depth):
    """'/x/y/#frag' -> '../../x/y/index.html#frag' relative to a page `depth` folders deep."""
    path, frag = (url.split('#', 1) + [''])[:2]
    up = '../' * depth
    if path.endswith('/'):
        path += 'index.html'
    out = up + path.lstrip('/')
    return out + ('#' + frag if frag else '')


for f in prev.rglob('*.html'):
    depth = len(f.relative_to(prev).parts) - 1
    t = f.read_text()
    t = re.sub(r'<meta name="robots"[^>]*>', '', t)
    t = t.replace('<head>', '<head>\n' + ROBOTS, 1)
    t = re.sub(r'(href|src)="(/(?!/)[^"]*)"', lambda m: f'{m.group(1)}="{rel_url(m.group(2), depth)}"', t)
    f.write_text(t)

css = prev / 'style.css'
css.write_text(css.read_text().replace('url("/fonts/', 'url("fonts/'))
(prev / 'robots.txt').write_text('User-agent: *\nDisallow: /\n')
(prev / 'README.md').write_text('Draft preview only (noindex). Generated by scripts/make_preview.py from site/. Not deployed.\n')
print('preview ->', prev)
